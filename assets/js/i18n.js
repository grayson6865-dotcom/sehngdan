  var lang = detect();

  function t(key, vars) {
    var table = DICT[lang] || DICT.en;
    var str = table[key] != null ? table[key] : (DICT.en[key] != null ? DICT.en[key] : key);
    if (vars) {
      str = str.replace(/\{(\w+)\}/g, function (m, k) {
        return vars[k] != null ? vars[k] : m;
      });
    }
    return str;
  }

  function set(next) {
    if (!DICT[next]) return false;
    lang = next;
    try { localStorage.setItem(STORAGE_KEY, next); } catch (e) {}
    if (global.document) {
      global.document.documentElement.lang = next === 'zh' ? 'zh-CN' : 'en';
      global.document.title = t('meta.title');
      var meta = document.querySelector('meta[name="description"]');
      if (meta) meta.setAttribute('content', t('meta.desc'));
    }
    return true;
  }

  function applyStatic() {
    var nodes = document.querySelectorAll('[data-i18n]');
    for (var i = 0; i < nodes.length; i++) {
      var textKey = nodes[i].getAttribute('data-i18n');
      var textVal = t(textKey);
      if (textVal !== textKey) nodes[i].textContent = textVal;
    }
    var htmlNodes = document.querySelectorAll('[data-i18n-html]');
    for (var j = 0; j < htmlNodes.length; j++) {
      var htmlKey = htmlNodes[j].getAttribute('data-i18n-html');
      var htmlVal = t(htmlKey);
      if (htmlVal !== htmlKey) htmlNodes[j].innerHTML = htmlVal;
    }
    var ariaNodes = document.querySelectorAll('[data-i18n-aria]');
    for (var k = 0; k < ariaNodes.length; k++) {
      var ariaKey = ariaNodes[k].getAttribute('data-i18n-aria');
      var ariaVal = t(ariaKey);
      if (ariaVal !== ariaKey) ariaNodes[k].setAttribute('aria-label', ariaVal);
    }
    var phNodes = document.querySelectorAll('[data-i18n-placeholder]');
    for (var l = 0; l < phNodes.length; l++) {
      var phKey = phNodes[l].getAttribute('data-i18n-placeholder');
      var phVal = t(phKey);
      if (phVal !== phKey) phNodes[l].setAttribute('placeholder', phVal);
    }
    var titleNodes = document.querySelectorAll('[data-i18n-title]');
    for (var m = 0; m < titleNodes.length; m++) {
      var titleKey = titleNodes[m].getAttribute('data-i18n-title');
      var titleVal = t(titleKey);
      if (titleVal !== titleKey) titleNodes[m].setAttribute('title', titleVal);
    }
  }

